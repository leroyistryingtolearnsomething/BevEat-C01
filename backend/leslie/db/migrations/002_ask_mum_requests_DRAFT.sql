BEGIN;

CREATE TABLE IF NOT EXISTS public.ask_mum_requests (
  request_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  child_id    integer NOT NULL REFERENCES public.child_profiles(child_id) ON DELETE CASCADE,
  item_id     integer NOT NULL REFERENCES public.menu_items(item_id),
  quantity    integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
  child_note  text CHECK (child_note IS NULL OR char_length(child_note) <= 200),  -- "I'm extra hungry today!"
  status      text NOT NULL DEFAULT 'pending'
              CHECK (status IN ('pending', 'approved', 'denied')),
  decided_by  integer REFERENCES public.users(user_id),   -- the parent who answered
  parent_note text CHECK (parent_note IS NULL OR char_length(parent_note) <= 200),
  order_id    integer REFERENCES public.orders(order_id), -- LEROY? set when an approved request is ordered
  created_at  timestamptz NOT NULL DEFAULT now(),
  decided_at  timestamptz,
  -- pending has no decision yet; approved/denied must say who and when
  CONSTRAINT ask_mum_decision_check CHECK (
    (status = 'pending'  AND decided_by IS NULL AND decided_at IS NULL)
    OR (status <> 'pending' AND decided_by IS NOT NULL AND decided_at IS NOT NULL)
  )
);
ALTER TABLE public.ask_mum_requests ENABLE ROW LEVEL SECURITY;

-- Parent inbox: "pending requests for my kids, newest first"
CREATE INDEX IF NOT EXISTS ask_mum_requests_child_status_idx
  ON public.ask_mum_requests (child_id, status, created_at DESC);

-- One open request per child per dish, so a kid can't spam the same ask.
CREATE UNIQUE INDEX IF NOT EXISTS ask_mum_requests_one_pending_idx
  ON public.ask_mum_requests (child_id, item_id) WHERE status = 'pending';

COMMIT;

