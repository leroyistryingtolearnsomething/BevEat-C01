BEGIN;

-- 1. Ask Mum requests ---------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ask_mum_requests (
  request_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  child_id     integer NOT NULL REFERENCES public.child_profiles(child_id) ON DELETE CASCADE,
  item_id      integer NOT NULL REFERENCES public.menu_items(item_id) ON DELETE CASCADE,
  status       text    NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'denied')),
  -- The Singapore day the request belongs to. "Just this once" = this day only.
  request_date date    NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Singapore')::date,
  parent_note  text    CHECK (parent_note IS NULL OR char_length(parent_note) <= 200),
  created_at   timestamptz NOT NULL DEFAULT now(),
  decided_at   timestamptz,
  CHECK ((status = 'pending') = (decided_at IS NULL))
);

-- One request per child, per dish, per day, whatever Mum answered (no spamming Mum)
CREATE UNIQUE INDEX IF NOT EXISTS ask_mum_one_per_day
  ON public.ask_mum_requests (child_id, item_id, request_date);
-- Parent inbox and "today's approvals" both look up by child + day
CREATE INDEX IF NOT EXISTS ask_mum_child_date
  ON public.ask_mum_requests (child_id, request_date);

ALTER TABLE public.ask_mum_requests ENABLE ROW LEVEL SECURITY;

-- 2. Mum's rules: allow a "no sugary drinks" rule next to "no fried food" ------
ALTER TABLE public.child_food_rules DROP CONSTRAINT IF EXISTS child_food_rules_rule_type_check;
ALTER TABLE public.child_food_rules ADD CONSTRAINT child_food_rules_rule_type_check
  CHECK (rule_type IN ('no_fried', 'no_sugary', 'blocked_item'));

-- 3. Menu data: is_fried was false for every dish, so "No fried food" locked nothing.
--    Mark the dishes that really are deep-fried or fried.
UPDATE public.menu_items SET is_fried = true
 WHERE name IN ('Nasi Lemak with Chicken Wing', 'Mee Goreng', 'Kids Ayam Goreng Set',
                'Roti John', 'Chicken Chop with Fries', 'Fish & Chips', 'Chicken Nuggets & Fries');

COMMIT;

