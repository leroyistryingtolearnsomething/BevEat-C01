-- WHAT IT DOES (all additive, safe for existing rows, safe to re-run)
--   1. menu_items.fibre_g, sugar_g     grams per serving, nullable
--   2. order_items.fibre_g, sugar_g    snapshot at order time, like calories
--   3. nutrient_guides table           daily guide per age band (kcal + 5
--                                      nutrients), one row marked is_default
--                                      for kids with no birth_year
--   4. fills fibre/sugar for dishes 1-30 (matched by name) and backfills old
--      order_items from their dish
--   5. v_order_summary also returns fibre_g and sugar_g
--
-- NOTE ON THE NUMBERS
--   Fibre/sugar per dish and the age guides are reasonable estimates for a
--   school prototype (HPB / WHO style daily guides for 4-12 year olds), not
--   lab values. Change them here or in the Table Editor: the app reads them
--   live, nothing is hard-coded in the code.
--
-- HOW TO RUN
--   Supabase dashboard -> "KiddyEats Team" -> SQL Editor -> New query ->
--   paste this whole file -> Run. All or nothing (BEGIN/COMMIT).
--
-- FOR RAGHAV (ordering): when you insert order_items, also copy
--   fibre_g and sugar_g from menu_items, the same way you copy calories.
--   Until then the app falls back to the dish's current values.
-- =============================================================================

BEGIN;

-- 1 + 2. Fibre and sugar --------------------------------------------------------
ALTER TABLE menu_items
  ADD COLUMN IF NOT EXISTS fibre_g numeric(6,1) CHECK (fibre_g >= 0),
  ADD COLUMN IF NOT EXISTS sugar_g numeric(6,1) CHECK (sugar_g >= 0);

ALTER TABLE order_items
  ADD COLUMN IF NOT EXISTS fibre_g numeric(6,1) CHECK (fibre_g >= 0),
  ADD COLUMN IF NOT EXISTS sugar_g numeric(6,1) CHECK (sugar_g >= 0);

-- 3. Daily guide by age ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS nutrient_guides (
  guide_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  age_from    smallint NOT NULL CHECK (age_from >= 0),
  age_to      smallint NOT NULL,
  kcal        integer  NOT NULL CHECK (kcal > 0),
  carbs_g     numeric(6,1) NOT NULL CHECK (carbs_g > 0),
  protein_g   numeric(6,1) NOT NULL CHECK (protein_g > 0),
  fat_g       numeric(6,1) NOT NULL CHECK (fat_g > 0),
  fibre_g     numeric(6,1) NOT NULL CHECK (fibre_g > 0),
  sugar_g     numeric(6,1) NOT NULL CHECK (sugar_g > 0),
  is_default  boolean NOT NULL DEFAULT false,
  source      text NOT NULL,
  CHECK (age_to >= age_from),
  UNIQUE (age_from, age_to)
);
-- at most one default row (used when a kid has no birth_year)
CREATE UNIQUE INDEX IF NOT EXISTS nutrient_guides_one_default ON nutrient_guides (is_default) WHERE is_default;
-- same as every other table: RLS on, no policies, only the Express backend reads it
ALTER TABLE nutrient_guides ENABLE ROW LEVEL SECURITY;

INSERT INTO nutrient_guides (age_from, age_to, kcal, carbs_g, protein_g, fat_g, fibre_g, sugar_g, is_default, source) VALUES
