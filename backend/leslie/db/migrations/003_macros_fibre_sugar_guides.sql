-- old orders get the dish's values as their snapshot
UPDATE order_items oi
   SET fibre_g = COALESCE(oi.fibre_g, m.fibre_g),
       sugar_g = COALESCE(oi.sugar_g, m.sugar_g)
  FROM menu_items m
 WHERE m.item_id = oi.item_id AND (oi.fibre_g IS NULL OR oi.sugar_g IS NULL);

-- 5. v_order_summary: same as before, plus fibre and sugar at the end -----------
CREATE OR REPLACE VIEW v_order_summary AS
SELECT o.order_id,
       o.child_id,
       o.stall_id,
       s.name AS stall_name,
       o.queue_number,
       o.status,
       o.total_amount,
       o.placed_at,
       COALESCE(SUM(oi.quantity * oi.calories), 0)::integer   AS calories,
       COALESCE(SUM(oi.quantity::numeric * oi.protein_g), 0)  AS protein_g,
       COALESCE(SUM(oi.quantity::numeric * oi.carbs_g), 0)    AS carbs_g,
       COALESCE(SUM(oi.quantity::numeric * oi.fat_g), 0)      AS fat_g,
       COALESCE(SUM(oi.quantity::numeric * oi.fibre_g), 0)    AS fibre_g,
       COALESCE(SUM(oi.quantity::numeric * oi.sugar_g), 0)    AS sugar_g
  FROM orders o
  JOIN stalls s ON s.stall_id = o.stall_id
  LEFT JOIN order_items oi ON oi.order_id = o.order_id
 GROUP BY o.order_id, s.name;

COMMIT;

