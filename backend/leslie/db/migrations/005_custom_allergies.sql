-- =============================================================================
-- KiddyEats migration 005: custom allergies typed in by a parent
-- Written 7 Nov 2026 by Leslie (schema owner).
--
-- WHY
--   The 9 preset allergens (allergens table) don't cover everything, e.g. kiwi,
--   mango, coconut, tomato. A parent can now type their own for each child.
--   Menu items are not tagged with these words, so a dish is blocked when the
--   word appears in its name, description or ingredients (whole word start,
--   case-insensitive, simple plurals: "strawberry" also blocks "strawberries").
--   "No chilli" / "without chilli" don't count, so a chilli-allergic kid still
--   gets the "No chilli" add-on. Otherwise it fails closed: "pea" also blocks
--   "peanut sauce".
--
-- WHAT IT DOES (additive, safe to re-run)
--   child_custom_allergies              one row per child per typed allergy
--   mentions_food(text, word)           the matching rule, in one place
--   v_child_custom_allergy_items        child_id, item_id, label, icon
--   v_child_custom_allergy_add_ons      child_id, add_on_id, label, icon
--   v_child_blocked_items               preset + custom in one list (for Home)
--
-- HOW TO RUN
--   Supabase dashboard -> "KiddyEats Team" -> SQL Editor -> paste -> Run.
-- =============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.child_custom_allergies (
  custom_allergy_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  child_id   int  NOT NULL REFERENCES public.child_profiles(child_id) ON DELETE CASCADE,
  label      text NOT NULL,
  icon       text NOT NULL DEFAULT '⚠️',
  created_at timestamptz NOT NULL DEFAULT now(),
  -- letters, spaces, hyphen, apostrophe; 2 to 40 characters (the API checks the same)
  CONSTRAINT child_custom_allergies_label_check CHECK (label ~ '^[A-Za-z][A-Za-z '' -]{1,39}$')
);
CREATE UNIQUE INDEX IF NOT EXISTS child_custom_allergies_one_each
  ON public.child_custom_allergies (child_id, lower(label));
ALTER TABLE public.child_custom_allergies ENABLE ROW LEVEL SECURITY;

-- true when `haystack` mentions `word` at the start of a word, ignoring case.
-- A trailing ies / y / es / s is dropped first so singular and plural both match.
-- Straight after "no " or "without " doesn't count ("No chilli" is safe for a chilli allergy).
CREATE OR REPLACE FUNCTION public.mentions_food(haystack text, word text)
RETURNS boolean
LANGUAGE sql IMMUTABLE
AS $$
  SELECT coalesce(haystack, '') ~* (
    '(?<!no )(?<!without )\m' || regexp_replace(
      CASE WHEN length(regexp_replace(lower(btrim(word)), '(ies|y|es|s)$', '')) >= 3
           THEN regexp_replace(lower(btrim(word)), '(ies|y|es|s)$', '')
           ELSE lower(btrim(word)) END,
      '([^a-z0-9])', '\\\1', 'g')
  )
$$;

CREATE OR REPLACE VIEW public.v_child_custom_allergy_items
WITH (security_invoker = true) AS
SELECT ca.child_id, m.item_id, ca.label, ca.icon
FROM public.child_custom_allergies ca
JOIN public.menu_items m
  ON public.mentions_food(concat_ws(' ', m.name, m.description, array_to_string(m.ingredients, ' ')), ca.label);

CREATE OR REPLACE VIEW public.v_child_custom_allergy_add_ons
WITH (security_invoker = true) AS
SELECT ca.child_id, ao.add_on_id, ao.item_id, ca.label, ca.icon
FROM public.child_custom_allergies ca
JOIN public.add_ons ao ON public.mentions_food(ao.name, ca.label);

-- Every dish a child must not get, and why. Preset tags + custom words.
CREATE OR REPLACE VIEW public.v_child_blocked_items
WITH (security_invoker = true) AS
SELECT ca.child_id, mia.item_id, a.name AS reason, 'preset'::text AS kind
FROM public.child_allergies ca
JOIN public.menu_item_allergens mia ON mia.allergen_id = ca.allergen_id
JOIN public.allergens a ON a.allergen_id = ca.allergen_id
UNION ALL
SELECT child_id, item_id, label, 'custom' FROM public.v_child_custom_allergy_items;

-- Self-check: the matching rule behaves as documented, or nothing is saved
DO $$
BEGIN
  IF NOT public.mentions_food('Fresh strawberries with cream', 'Strawberry') THEN
    RAISE EXCEPTION 'Check failed: plural match';
  END IF;
  IF NOT public.mentions_food('Coconut rice', 'coconut') THEN
    RAISE EXCEPTION 'Check failed: plain match';
  END IF;
  IF public.mentions_food('Chicken rice with cucumber', 'cucumberx') THEN
    RAISE EXCEPTION 'Check failed: false match';
  END IF;
  IF public.mentions_food('Pineapple tart', 'apple') THEN
    RAISE EXCEPTION 'Check failed: matched inside a word';
  END IF;
  IF public.mentions_food('Kids set. No chilli.', 'Chilli') OR NOT public.mentions_food('Less chilli sauce', 'Chilli') THEN
    RAISE EXCEPTION 'Check failed: "no chilli" rule';
  END IF;
END $$;

COMMIT;
